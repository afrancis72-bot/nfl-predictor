"""Portfolio-level selection of prevalidated DraftKings lineup candidates.

Candidates are generated by the existing lineup builder, retaining its salary,
roster, stacking, and eligibility checks. This module selects the portfolio
jointly rather than greedily exhausting player exposures.
"""
from collections import Counter
from itertools import combinations
import numpy as np
from scipy.optimize import milp, Bounds, LinearConstraint
from scipy.sparse import lil_matrix

def select_portfolio(candidates, n=20, exposure_cap=.35, locked_ids=(),
                     upside_fraction=.25, pair_soft_cap=4,
                     pair_penalty=.30, floor_weight=.35,
                     overlap_penalty=.10, time_limit=40):
    """Return (selected candidates, diagnostics).

    Each candidate: {'ids': iterable of player IDs, 'projection': float,
    'upside': bool, optional 'ceiling': float}.
    Locked players are exempt from exposure caps and diversity penalties.
    Caller must supply a sufficiently large, distinct candidate bank.
    """
    locked=set(map(str,locked_ids))
    pool=[]
    seen=set()
    for c in candidates:
        ids=frozenset(map(str,c['ids']))
        if not locked.issubset(ids) or len(ids)!=9 or ids in seen:
            continue
        seen.add(ids)
        pool.append(dict(c,ids=ids))
    m=len(pool)
    if m<n: raise ValueError(f'Need at least {n} unique valid candidates; got {m}')
    cap=int(np.floor(n*exposure_cap+1e-9))
    players=sorted(set().union(*(c['ids'] for c in pool))-locked)
    pairs=Counter(pair for c in pool for pair in combinations(sorted(c['ids']-locked),2))
    repeated=[pair for pair,count in pairs.items() if count>pair_soft_cap]
    # Variables: candidate binary x, pair overuse slack >=0, floor t.
    k=len(repeated); floor_idx=m+k; size=floor_idx+1
    rows=[]; lows=[]; highs=[]
    def row(vals,lo=-np.inf,hi=np.inf):
        rows.append(vals);lows.append(lo);highs.append(hi)
    row({i:1 for i in range(m)},n,n)
    for p in players:
        row({i:1 for i,c in enumerate(pool) if p in c['ids']},hi=cap)
    upside_count=round(n*upside_fraction)
    row({i:1 for i,c in enumerate(pool) if c.get('upside',False)},
        upside_count,upside_count)
    for j,pair in enumerate(repeated):
        vals={i:1 for i,c in enumerate(pool) if set(pair).issubset(c['ids'])}
        vals[m+j]=-1
        row(vals,hi=pair_soft_cap)
    # Every selected lineup must clear the optimized portfolio floor.
    big=max(float(c['projection']) for c in pool)+100
    for i,c in enumerate(pool):
        row({floor_idx:1,i:big},hi=float(c['projection'])+big)
    A=lil_matrix((len(rows),size),dtype=float)
    for r,vals in enumerate(rows):
        for j,v in vals.items(): A[r,j]=v
    obj=np.zeros(size)
    for i,c in enumerate(pool):
        obj[i]=-float(c['projection'])-(
            .15*float(c.get('ceiling',c['projection'])) if c.get('upside') else 0)
    obj[m:m+k]=pair_penalty
    obj[floor_idx]=-floor_weight*n
    lower=np.zeros(size);upper=np.full(size,np.inf)
    upper[:m]=1
    upper[floor_idx]=max(float(c['projection']) for c in pool)
    integrality=np.zeros(size,dtype=int);integrality[:m]=1
    result=milp(obj,integrality=integrality,bounds=Bounds(lower,upper),
                constraints=LinearConstraint(A.tocsr(),lows,highs),
                options={'time_limit':time_limit,'mip_rel_gap':.02})
    if result.x is None: raise RuntimeError(
        f'Portfolio optimization infeasible or timed out: {result.message}')
    chosen=[pool[i] for i in range(m) if result.x[i]>.5]
    if len(chosen)!=n: raise RuntimeError('Solver did not return complete portfolio')
    counts=Counter(p for c in chosen for p in c['ids'])
    pair_counts=Counter(p for c in chosen for p in
                        combinations(sorted(c['ids']-locked),2))
    projections=[float(c['projection']) for c in chosen]
    return chosen, {'average_projection':float(np.mean(projections)),
                    'weakest_projection':min(projections),
                    'strongest_projection':max(projections),
                    'exposures':dict(counts),
                    'pair_frequencies':{str(p):v for p,v in pair_counts.items()},
                    'upside_count':sum(bool(c.get('upside')) for c in chosen),
                    'solver_status':str(result.message)}
