def _allowed_url(url):
    if not isinstance(url,str):
        raise ValueError("Official source URL is required")
    parsed=urlparse(url)
    if (parsed.scheme!="https" or parsed.hostname not in ALLOWED_HOSTS
        or not parsed.path.startswith(ALLOWED_URL_PATH)
        or parsed.username or parsed.password or parsed.port is not None
        or parsed.fragment):
        raise ValueError("Only exact NFL.com HTTPS /news/ article URLs are supported")
    return url


def fetch_official_html(url,*,client=None):
    """Fetch official bytes without redirects, fallback hosts or caching.

    Network errors or unknown publisher response formats fail closed. Capture
    metadata is generated by the program, not provided by a user.
    """
    url=_allowed_url(url)
    client=client or requests
    response=client.get(url,headers={
        "User-Agent":"TeamAI2ResearchOfficialInactiveCapture/1.0 (+https://www.nfl.com/inactives/)",
        "Accept":"text/html,application/xhtml+xml",
    },timeout=15,allow_redirects=False)
    if response.status_code!=200:
        raise ValueError(f"Official source not directly accessible: HTTP {response.status_code}")
    if response.url!=url:
        raise ValueError("Official source URL unexpectedly changed")
    kind=response.headers.get("Content-Type","").lower()
    if not (kind.startswith("text/html") or kind.startswith("application/xhtml+xml")):
        raise ValueError("Official source response is not HTML")
    raw=response.content
    if not isinstance(raw,bytes) or not (200<len(raw)<=MAX_BYTES):
        raise ValueError("Official source HTML response is empty or oversized")
    return raw


def _article_date(soup):
    dates=[]
    for meta in soup.select('meta[property="article:published_time"],'
                            'meta[name="article:published_time"],'
                            'meta[itemprop="datePublished"],'
                            'meta[property="og:published_time"]'):
        val=meta.get("content")
        if val:
            dates.append(val)
    for tag in soup.find_all("script",attrs={"type":"application/ld+json"}):
        try:
            block=json.loads(tag.get_text() or "{}")
        except (ValueError,TypeError):
            continue
        blocks=block if isinstance(block,list) else [block]
        for item in blocks:
            if isinstance(item,dict):
                if "datePublished" in item:
                    dates.append(item["datePublished"])
                for graph in item.get("@graph",[]):
                    if isinstance(graph,dict) and "datePublished" in graph:
                        dates.append(graph["datePublished"])
    observed=set()
    for value in dates:
        try:
            observed.add(_utc(value,"article publication").isoformat())
        except (ValueError,TypeError):
            continue
    if len(observed)!=1:
        raise ValueError("NFL article needs one consistent machine-readable published UTC time")
    return observed.pop()


def _team_heading(value):
    normalized=" ".join(str(value).upper().split())
    return _TEAM_NICKNAMES.get(normalized) or _TEAM_ALIASES.get(normalized)


def _player_name_from_list(li):
    # Extract only simple bullet text with a position prefix; never parse
    # a player found in an unrelated article paragraph or navigation link.
    value=" ".join(li.get_text(" ",strip=True).split())
    match=_NAME_LINE.fullmatch(value)
    if not match:
        return None
    pos,name=match.groups()
    # Parenthetical caveats can mean the emergency third quarterback;
    # these are still on the official list, so retain the text only as
    # a note and never infer anything about positive ACTIVE players.
    note=""
    if name.endswith(")") and "(" in name:
        name,note=name.rsplit("(",1)
        name=name.strip()
        note=note[:-1].strip()
    if not name or len(name)>80 or not re.match(r"^[A-Za-zÀ-ÿ]",name):
        raise ValueError("Inactive player entry has invalid identity")
    return pos.upper(),name,note


def parse_official_inactive_article(raw,url,*,season,week,game):
    """Extract official OUT names; no fabricated pregame capture time.

    Parsing a past article is allowed, but no result of this parser alone
    is a valid pregame status snapshot. That requires capture BEFORE kickoff.
    """
    _allowed_url(url)
    if not isinstance(raw,(bytes,bytearray)) or len(raw)>MAX_BYTES:
        raise ValueError("Invalid official HTML bytes")
    soup=BeautifulSoup(bytes(raw),"html.parser")
    title=soup.title.get_text(" ",strip=True) if soup.title else ""
    h1=soup.find("h1")
    headline=h1.get_text(" ",strip=True) if h1 else title
    text=(headline+" "+title).lower()
    if "inactive" not in text or f"week {int(week)}" not in text:
        raise ValueError("Article does not identify target week inactive report")
    published=_article_date(soup)
    if _utc(published,"article published").year!=int(season):
        raise ValueError("Official inactive article is not from target NFL season")
    teams=str(game).split("@")
    if len(teams)!=2 or any(not t for t in teams):
        raise ValueError("Invalid two-team matchup identity")
    target=tuple(canonical_team(t) for t in teams)
    if len(set(target))!=2:
        raise ValueError("Invalid same-team matchup")

    root=None
    for node in soup.select(
        "article, .nfl-c-article__body, .nfl-c-article__content,"
        " .nfl-c-article__container, [data-testid='article-content'],"
        " main"):
        headings=[_team_heading(h.get_text(" ",strip=True))
                  for h in node.find_all("h3")]
        if set(target).issubset(set(headings)):
            root=node
            break
    if root is None:
        # Do not search global navigation text: if a verified story body
        # or the site's explicit <main> landmark containing BOTH exact team
        # headings cannot be identified, refuse to infer inactive rows.
        raise ValueError("Official article body with both team lists not found")

    by_team={}
    heading_order=[]
    current=None
    for node in root.find_all(["h2","h3","li"]):
        if node.name=="h2":
            current=None
            continue
        if node.name=="h3":
            current=_team_heading(node.get_text(" ",strip=True))
            if current is not None:
                heading_order.append(current)
                if current in by_team:
                    raise ValueError("Duplicate official team heading is ambiguous")
                by_team[current]=[]
            continue
        if node.name=="li" and current in target:
            candidate=_player_name_from_list(node)
            if candidate:
                by_team[current].append(candidate)
    a,b=target
    if (a not in by_team or b not in by_team
        or not 3<=len(by_team[a])<=12 or not 3<=len(by_team[b])<=12):
        raise ValueError("Missing, incomplete, or implausible official game inactive list")
    positions=[(i,t) for i,t in enumerate(heading_order) if t in target]
    if len(positions)!=2 or abs(positions[0][0]-positions[1][0])!=1:
        raise ValueError("Team inactive sections are not adjacent as a game pair")
    for team in target:
        names=[name.lower() for _,name,_ in by_team[team]]
        if len(names)!=len(set(names)):
            raise ValueError("Duplicated inactive player identity in official team list")
    return {
        "source_url":url,
        "published_at_utc":published,
        "headline":headline,
        "season":int(season),"week":int(week),"game":str(game),
        "inactive_by_team":{
            team:[{"position":p,"player":n,"note":note}
                  for p,n,note in by_team[team]]
            for team in target
        },
        "source_html_sha256":hashlib.sha256(bytes(raw)).hexdigest(),
        "verified_out_only":True,
        "verified_active_from_omission":False,
        "team_heading_order":heading_order,
    }


def make_pregame_snapshot(parsed,*,kickoff_utc,captured_at_utc):
    """Create source-derived OUT-only status records for a real pregame capture.

    If article is fetched after kickoff, or was published after capture, it is
    not eligible to be used retrospectively as a pregame forecast input.
    """
    kickoff=_utc(kickoff_utc,"kickoff_utc")
    capture=_utc(captured_at_utc,"captured_at_utc")
    if capture>=kickoff:
        raise ValueError("Past-kickoff source capture is not pregame evidence")
    if _utc(parsed["published_at_utc"],"published_at_utc")>capture:
        raise ValueError("Article published after collection: clock/source mismatch")
    rows=[]
    for team,players in parsed["inactive_by_team"].items():
        for player in players:
            rows.append({
                "team":team,"player":player["player"],
                "status":OUT,"source_type":"NFL_OFFICIAL_INACTIVES",
                "source_url":parsed["source_url"],
                "published_at_utc":parsed["published_at_utc"],
                "source_html_sha256":parsed["source_html_sha256"],
                "source_evidence_type":"OFFICIAL_ARTICLE_TEAM_INACTIVE_BULLET",
            })
    result={
        "season":parsed["season"],"week":parsed["week"],"game":parsed["game"],
        "kickoff_utc":kickoff.isoformat(),
        "captured_at_utc":capture.isoformat(),
        "records":rows,
    }
    validate_availability_snapshot(
        result,season=parsed["season"],week=parsed["week"],game=parsed["game"],
        as_of_utc=capture.isoformat())
    return result


def verify_snapshot_against_raw_html(raw,parsed,snapshot):
    """Reparse frozen official content and compare EVERY status/evidence field.

    Revalidates the content digest and player lists; fails if player statuses,
    teams, source or timing have been modified since collection. This is a
    content-authentication step, not cryptographic proof of NFL authorship.
    """
    fresh=parse_official_inactive_article(
        raw,parsed["source_url"],season=parsed["season"],
        week=parsed["week"],game=parsed["game"])
    if fresh!=parsed:
        raise ValueError("Archived NFL inactive parser data differs from source HTML")
    expected=make_pregame_snapshot(
        fresh,kickoff_utc=snapshot["kickoff_utc"],
        captured_at_utc=snapshot["captured_at_utc"])
    if expected!=snapshot:
        raise ValueError("Archived NFL inactive statuses/timestamps altered")
    return True


def save_new_capture(raw,parsed,snapshot,out_dir,*,real_network_fetch=True):
    """Write exact evidence bytes plus hashes to a new non-overwriting directory.

    A GitHub Actions artifact that stores this directory can be inspected
    later; it is retained subject to artifact retention, not forever.
    """
    if not real_network_fetch:
        raise ValueError("Synthetic HTML must never be archived as authentic NFL capture")
    verify_snapshot_against_raw_html(raw,parsed,snapshot)
    root=Path(out_dir)
    if root.exists():
        raise FileExistsError("An existing source snapshot must not be overwritten")
    root.mkdir(parents=True,exist_ok=False)
    (root/"official_source.html").write_bytes(raw)
    (root/"inactive_player_snapshot.json").write_text(
        json.dumps(snapshot,indent=2,sort_keys=True,allow_nan=False))
    (root/"verified_parser.json").write_text(
        json.dumps(parsed,indent=2,sort_keys=True,allow_nan=False))
    metadata={
        "archive_type":"NFL_OFFICIAL_INACTIVES_PREGAME_CAPTURE",
        "capture_utc":snapshot["captured_at_utc"],
        "kickoff_utc":snapshot["kickoff_utc"],
        "source_url":parsed["source_url"],
        "source_html_sha256":parsed["source_html_sha256"],
        "source_reparsed_and_statuses_matched":True,
        "http_capture_was_performed_by_this_program":True,
        "official_article_proves_only_out_players":True,
        "positive_active_claims_prohibited":True,
        "production_approved":False,
    }
    (root/"manifest.json").write_text(json.dumps(metadata,indent=2,sort_keys=True))
    return str(root)
