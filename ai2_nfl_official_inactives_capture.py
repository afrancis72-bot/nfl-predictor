"""Official NFL.com inactive-article capture and content-verified OUT evidence.

A source URL is not proof. This module downloads the *actual* NFL.com HTML,
restricts it to an NFL inactives article, checks its publication timestamp and
game/week identity, extracts only players inside BOTH target-team inactive
lists, and retains the exact raw HTML and SHA-256.

Unlisted players remain UNKNOWN, never become verified ACTIVE by omission.
No post-kickoff capture is accepted for a pregame snapshot. A postgame page
may be used for parser smoke tests only, never for historical pregame claims.

This first collector only supports explicit official INACTIVE decisions.
It does NOT establish the complete game-day active roster.
"""
